-- Migration additionnelle — tables de segments communautaires.
--
-- Ces deux tables n'existaient qu'en DDL d'exécution (services/mediaSegments/
-- communityStore.js, syntaxe MySQL) et donc dans aucune migration : un
-- PostgreSQL neuf ne les avait pas. Le rendu généré ne les couvre pas non plus
-- (elles ne sont pas dans db/schema), d'où ce fichier écrit à la main.
--
-- ENUM devient VARCHAR + CHECK : PostgreSQL refuserait la syntaxe MySQL, et un
-- type énuméré natif imposerait une migration pour chaque nouvelle valeur.

CREATE TABLE IF NOT EXISTS "segment_submissions" (
  "id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "media_type" VARCHAR(16) NOT NULL,
  "tmdb_id" INTEGER NOT NULL,
  "season" SMALLINT NOT NULL DEFAULT -1,
  "episode" SMALLINT NOT NULL DEFAULT -1,
  "reference_duration_ms" INTEGER NOT NULL,
  "segment_type" VARCHAR(16) NOT NULL,
  "start_ms" INTEGER NOT NULL,
  "end_ms" INTEGER NOT NULL,
  "author_user_type" VARCHAR(16) NOT NULL,
  "author_user_id" VARCHAR(255) NOT NULL,
  "author_label" VARCHAR(64) DEFAULT NULL NULL,
  "votes_up" INTEGER NOT NULL DEFAULT 0,
  "votes_down" INTEGER NOT NULL DEFAULT 0,
  "score" INTEGER NOT NULL DEFAULT 0,
  "created_at" TIMESTAMPTZ DEFAULT now() NOT NULL,
  "updated_at" TIMESTAMPTZ DEFAULT now() NOT NULL,
  PRIMARY KEY ("id"),
  -- Une seule proposition par type de séquence et par auteur : l'upsert du
  -- store s'appuie sur cette contrainte.
  CONSTRAINT "uniq_author_segment" UNIQUE (
    "media_type", "tmdb_id", "season", "episode", "segment_type",
    "author_user_type", "author_user_id"
  ),
  CONSTRAINT "segment_media_type_allowed" CHECK ("media_type" IN ('tv', 'movie')),
  CONSTRAINT "segment_type_allowed" CHECK ("segment_type" IN ('intro', 'recap', 'outro', 'credits', 'preview')),
  CONSTRAINT "segment_author_type_allowed" CHECK ("author_user_type" IN ('oauth', 'bip39'))
);

CREATE INDEX IF NOT EXISTS "idx_segment_lookup"
  ON "segment_submissions" ("media_type", "tmdb_id", "season", "episode");
CREATE INDEX IF NOT EXISTS "idx_segment_adopted"
  ON "segment_submissions" ("media_type", "tmdb_id", "season", "episode", "score");

CREATE TABLE IF NOT EXISTS "segment_votes" (
  "submission_id" BIGINT NOT NULL,
  "voter_user_type" VARCHAR(16) NOT NULL,
  "voter_user_id" VARCHAR(255) NOT NULL,
  "value" SMALLINT NOT NULL,
  "weight" SMALLINT NOT NULL DEFAULT 1,
  "created_at" TIMESTAMPTZ DEFAULT now() NOT NULL,
  "updated_at" TIMESTAMPTZ DEFAULT now() NOT NULL,
  PRIMARY KEY ("submission_id", "voter_user_type", "voter_user_id"),
  CONSTRAINT "segment_votes_submission_fk"
    FOREIGN KEY ("submission_id") REFERENCES "segment_submissions" ("id") ON DELETE CASCADE,
  CONSTRAINT "segment_voter_type_allowed" CHECK ("voter_user_type" IN ('oauth', 'bip39'))
);
